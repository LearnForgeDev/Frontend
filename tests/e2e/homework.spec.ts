import type { HomeworkAttemptDto, HomeworkDto } from '../../src/Endpoints/Homework/homework.type';
import { test, expect } from './fixtures';
import { readJson } from './flows.utils';
import { createHomework, handwrittenFixture, HOMEWORK_API, homeworkPath } from './homework.utils';

test('homework: five answer types, private hints and released image feedback survive reloads', async ({ actors }, testInfo) => {
  const teacher = await actors('teacher');
  const student = await actors('student');
  const homework = await createHomework(teacher.page, [student.identity.userPublicId]);
  const studentDefinition = await readJson<HomeworkDto>(await student.page.request.get(`${HOMEWORK_API}/${homework.publicId}`));
  expect(JSON.stringify(studentDefinition)).not.toContain('teacherHint');
  expect(JSON.stringify(studentDefinition)).not.toContain('isCorrect');
  await student.page.goto(homeworkPath(homework.publicId));
  await student.page.getByRole('button', { name: 'Начать выполнение' }).click();
  await expect(student.page).toHaveURL(/\/attempts\/[0-9a-f-]+/);
  await expect(student.page.getByRole('region', { name: 'Вопрос 1', exact: true })).toBeVisible();
  await student.page.getByRole('region', { name: 'Вопрос 1', exact: true }).getByRole('button', { name: 'Показать подсказку' }).click();
  await expect(student.page.getByRole('dialog', { name: 'Подсказка', exact: true })).toContainText('Начните с определения.');
  await expect(student.page.getByText('Приватная заметка преподавателю.')).toHaveCount(0);
  await student.page.keyboard.press('Escape');
  await student.page.getByRole('textbox', { name: 'Ваш ответ', exact: true }).fill('Определение и объяснение.');
  await student.page.getByRole('textbox', { name: 'Ваш развёрнутый ответ' }).fill('Подробное решение с проверкой результата.');
  await student.page.getByRole('region', { name: 'Вопрос 3', exact: true }).getByRole('radio', { name: 'Первый верный' }).check();
  await student.page.getByRole('region', { name: 'Вопрос 4', exact: true }).getByRole('checkbox', { name: 'Первый верный' }).check();
  await student.page.getByRole('region', { name: 'Вопрос 4', exact: true }).getByRole('checkbox', { name: 'Второй верный' }).check();
  const chooser = student.page.waitForEvent('filechooser');
  await student.page.getByRole('button', { name: 'Прикрепить файл' }).click();
  await (await chooser).setFiles(await handwrittenFixture(student.page));
  await expect(student.page.getByAltText('решение.png')).toBeVisible();
  await student.page.getByRole('button', { name: 'Сохранить ответы', exact: true }).click();
  await expect(student.page.getByText('Ответы сохранены на сервере.', { exact: true })).toBeVisible();
  const attemptPath = new URL(student.page.url()).pathname;
  await student.page.reload();
  await expect(student.page.getByRole('textbox', { name: 'Ваш ответ', exact: true })).toHaveValue('Определение и объяснение.');
  await expect(student.page.getByRole('textbox', { name: 'Ваш развёрнутый ответ' })).toContainText('Подробное решение с проверкой результата.');
  await student.page.getByRole('button', { name: 'Сдать работу', exact: true }).click();
  await expect(student.page.getByText(/версия 1 · Проверяется/)).toBeVisible();
  await teacher.page.goto(`${attemptPath}/review`);
  for (let question = 1; question <= 5; question++) {
    await teacher.page.getByRole('spinbutton', { name: `Баллы за вопрос ${question}`, exact: true }).fill('1');
  }
  await teacher.page.getByRole('button', { name: 'Добавить область' }).click();
  await teacher.page.getByRole('textbox', { name: 'Комментарий к области', exact: true }).fill('В этой строке должно быть 4.');
  await teacher.page.getByRole('textbox', { name: 'Общий комментарий', exact: true }).fill('Проверьте вычисления в работе от руки.');
  await teacher.page.getByRole('button', { name: 'Сохранить приватный черновик' }).click();
  await expect(teacher.page.getByText('Черновик проверки сохранён.', { exact: true })).toBeVisible();
  const attemptId = attemptPath.split('/').at(-1);
  const pending = await readJson<HomeworkAttemptDto>(await student.page.request.get(`${HOMEWORK_API}/attempts/${attemptId}`));
  expect(pending.score).toBeNull();
  expect(pending.answers.flatMap(answer => answer.annotations)).toEqual([]);
  expect(JSON.stringify(pending)).not.toContain('В этой строке должно быть 4.');
  await teacher.page.reload();
  await expect(teacher.page.getByRole('button', { name: 'Область 1: В этой строке должно быть 4.' })).toBeVisible();
  await teacher.page.getByRole('button', { name: 'Завершить проверку', exact: true }).click();
  await expect(teacher.page.getByText(/версия 1 · Проверено/)).toBeVisible();
  await student.page.reload();
  await expect(student.page.getByText('Результат: 5 / 6 баллов.', { exact: true })).toBeVisible();
  await expect(student.page.getByRole('button', { name: 'Область 1: В этой строке должно быть 4.' })).toBeVisible();
  await expect(student.page.getByRole('button', { name: 'Добавить область' })).toHaveCount(0);
  await student.page.setViewportSize({ width: 390, height: 844 });
  expect(await student.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await student.page.screenshot({ path: testInfo.outputPath('homework-reviewed-mobile.png'), fullPage: true });
});

test('homework: queued version blocks new starts and the server completes a forced countdown', async ({ actors }, testInfo) => {
  test.setTimeout(150000);
  const teacher = await actors('teacher');
  const student = await actors('student');
  const nextStudent = await actors('second-student');
  const homework = await createHomework(teacher.page, [student.identity.userPublicId, nextStudent.identity.userPublicId], false);
  const path = homeworkPath(homework.publicId);
  await student.page.goto(path);
  await student.page.getByRole('button', { name: 'Начать выполнение' }).click();
  await student.page.getByRole('textbox', { name: 'Ваш ответ', exact: true }).fill('Сохранённый ответ первой версии.');
  await student.page.getByRole('button', { name: 'Сохранить ответы', exact: true }).click();
  await expect(student.page.getByText('Ответы сохранены на сервере.', { exact: true })).toBeVisible();
  const attemptId = new URL(student.page.url()).pathname.split('/').at(-1);
  await teacher.page.goto(path);
  await teacher.page.getByRole('button', { name: 'Редактировать', exact: true }).click();
  await teacher.page.getByRole('button', { name: 'Опубликовать версию 2', exact: true }).click();
  await expect(teacher.page.getByText('Версия 2 ожидает публикации', { exact: true })).toBeVisible();
  await nextStudent.page.goto(path);
  await expect(nextStudent.page.getByRole('button', { name: 'Начать выполнение' })).toBeDisabled();
  expect((await nextStudent.page.request.post(`${HOMEWORK_API}/${homework.publicId}/attempts`)).status()).toBe(409);
  await teacher.page.getByRole('button', { name: 'Завершить через 60 секунд' }).click();
  await expect(student.page.getByText(/Преподаватель завершает работу\. Осталось/)).toBeVisible({ timeout: 20000 });
  await student.page.screenshot({ path: testInfo.outputPath('homework-force-warning.png'), fullPage: true });
  await expect.poll(async () => {
    const attempt = await readJson<HomeworkAttemptDto>(await student.page.request.get(`${HOMEWORK_API}/attempts/${attemptId}`));
    return attempt.wasForced;
  }, { timeout: 80000, intervals: [1000, 3000] }).toBe(true);
  await expect(student.page.getByText('Попытка сдана автоматически. Неотвеченные вопросы оценены в ноль баллов.', { exact: true })).toBeVisible({ timeout: 20000 });
  await expect.poll(async () => (await readJson<HomeworkDto>(await teacher.page.request.get(`${HOMEWORK_API}/${homework.publicId}`))).activeVersion, { timeout: 15000 }).toBe(2);
  const original = await readJson<HomeworkAttemptDto>(await student.page.request.get(`${HOMEWORK_API}/attempts/${attemptId}`));
  expect(original.version).toBe(1);
  expect(original.answers[0].textValue).toBe('Сохранённый ответ первой версии.');
  await nextStudent.page.reload();
  await nextStudent.page.getByRole('button', { name: 'Начать выполнение' }).click();
  await expect(nextStudent.page.getByText(/версия 2 · Черновик/)).toBeVisible();
});
